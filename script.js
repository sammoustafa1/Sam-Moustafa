const introScreen = document.getElementById('introScreen');
const introEnter = document.getElementById('introEnter');
const pageSections = [document.querySelector('.site-header'), document.querySelector('main'), document.querySelector('.site-footer')];
const maxIntroScrollHandoff = 72;
let pendingIntroScroll = 0;

function closeIntro() {
  if (!introScreen.classList.contains('is-active') || introScreen.classList.contains('is-opening')) return;
  introScreen.classList.add('is-opening');
}

function closeIntroAndScroll(distance) {
  if (!introScreen.classList.contains('is-active')) return;
  if (distance > 0) pendingIntroScroll = Math.min(maxIntroScrollHandoff, pendingIntroScroll + distance);
  closeIntro();
}

introEnter.addEventListener('click', closeIntro);
document.addEventListener('keydown', event => {
  if (event.key === 'Escape') {
    closeIntro();
  } else if (['ArrowDown', 'PageDown'].includes(event.key)) {
    event.preventDefault();
    closeIntroAndScroll(maxIntroScrollHandoff);
  }
});
window.addEventListener('wheel', event => {
  if (!introScreen.classList.contains('is-active')) return;
  event.preventDefault();
  closeIntroAndScroll(event.deltaY);
}, { passive: false });
let introTouchStartY = null;
introScreen.addEventListener('touchstart', event => {
  introTouchStartY = event.changedTouches[0].clientY;
}, { passive: true });
introScreen.addEventListener('touchmove', event => {
  if (introTouchStartY === null) return;
  const currentY = event.changedTouches[0].clientY;
  const swipeDistance = introTouchStartY - currentY;
  if (Math.abs(swipeDistance) <= 10) return;
  event.preventDefault();
  closeIntroAndScroll(swipeDistance);
  introTouchStartY = currentY;
}, { passive: false });
introScreen.addEventListener('touchend', () => { introTouchStartY = null; }, { passive: true });
introScreen.addEventListener('animationend', event => {
  if (event.target !== introScreen || event.animationName !== 'intro-open') return;
  introScreen.classList.remove('is-active', 'is-opening');
  introScreen.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('intro-open');
  pageSections.forEach(section => { section.inert = false; });
  document.querySelector('.hero-actions .button-primary').focus({ preventScroll: true });
  if (pendingIntroScroll > 0) window.scrollBy(0, pendingIntroScroll);
  pendingIntroScroll = 0;
});
pageSections.forEach(section => { section.inert = true; });
document.body.classList.add('intro-open');
introScreen.classList.add('is-active');
introScreen.setAttribute('aria-hidden', 'false');
requestAnimationFrame(() => introEnter.focus({ preventScroll: true }));

const leadForm = document.getElementById('leadForm');
const leadFormStatus = document.getElementById('leadFormStatus');

leadForm.addEventListener('submit', async event => {
  event.preventDefault();
  if (!leadForm.reportValidity()) return;

  const formData = new FormData(leadForm);
  if (String(formData.get('website') || '').trim()) return;

  const config = window.SITE_CONFIG || {};
  if (!config.supabaseUrl || !config.supabaseAnonKey) {
    leadFormStatus.dataset.message = 'leadNotConfigured';
    leadFormStatus.textContent = translations[language].leadNotConfigured;
    leadFormStatus.dataset.kind = 'error';
    return;
  }

  const submitButton = leadForm.querySelector('button[type="submit"]');
  submitButton.disabled = true;
  submitButton.querySelector('span:first-child').textContent = translations[language].sendingLead;
  leadFormStatus.textContent = '';
  delete leadFormStatus.dataset.kind;
  delete leadFormStatus.dataset.message;

  const payload = {
    name: String(formData.get('name')).trim(),
    email: String(formData.get('email')).trim(),
    phone: String(formData.get('phone') || '').trim() || null,
    interest: String(formData.get('interest') || '').trim() || null,
    message: String(formData.get('message') || '').trim() || null
  };

  try {
    const response = await fetch(`${config.supabaseUrl.replace(/\/$/, '')}/rest/v1/leads`, {
      method: 'POST',
      headers: {
        apikey: config.supabaseAnonKey,
        Authorization: `Bearer ${config.supabaseAnonKey}`,
        'Content-Type': 'application/json',
        Prefer: 'return=minimal'
      },
      body: JSON.stringify(payload)
    });
    if (!response.ok) {
      const details = await response.text();
      throw new Error(`Supabase returned HTTP ${response.status}: ${details}`);
    }
    leadForm.reset();
    leadFormStatus.dataset.message = 'leadSuccess';
    leadFormStatus.textContent = translations[language].leadSuccess;
    leadFormStatus.dataset.kind = 'success';
  } catch (error) {
    console.error('Could not submit lead to Supabase:', error);
    leadFormStatus.dataset.message = 'leadFailure';
    leadFormStatus.textContent = translations[language].leadFailure;
    leadFormStatus.dataset.kind = 'error';
  } finally {
    submitButton.disabled = false;
    submitButton.querySelector('span:first-child').textContent = translations[language].submitLead;
  }
});