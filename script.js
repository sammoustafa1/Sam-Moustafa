let language = 'ar';
let properties = [...sampleProperties];
let activeFilter = 'all';

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  const isArabic = language === 'ar';
  document.documentElement.lang = language;
  document.documentElement.dir = isArabic ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const value = translations[language][element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const value = translations[language][element.dataset.i18nPlaceholder];
    if (value) element.placeholder = value;
  });
  const formStatus = document.getElementById('leadFormStatus');
  if (formStatus && formStatus.dataset.message) {
    formStatus.textContent = translations[language][formStatus.dataset.message];
  }
  const formSubmitLabel = document.querySelector('#leadForm button[type="submit"] span:first-child');
  if (formSubmitLabel) {
    formSubmitLabel.textContent = translations[language][
      formSubmitLabel.closest('button').disabled ? 'sendingLead' : 'submitLead'
    ];
  }
  document.getElementById('languageToggle').textContent = isArabic ? 'EN' : 'عربي';
  document.getElementById('languageToggle').setAttribute('aria-label', isArabic ? 'Switch to English' : 'التبديل إلى العربية');
  document.getElementById('introLanguageToggle').textContent = isArabic ? 'EN' : 'عربي';
  document.getElementById('introLanguageToggle').setAttribute('aria-label', isArabic ? 'Switch to English' : 'التبديل إلى العربية');
  const notice = document.getElementById('siteNotice');
  if (!notice.hidden) notice.textContent = translations[language].fetchError;
  document.querySelectorAll('.filter-button').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.filter === activeFilter));
  });
  renderProperties();
}

function renderProperties() {
  const grid = document.getElementById('propertyGrid');
  const visible = properties.filter(property => activeFilter === 'all' || property.status === activeFilter);
  grid.replaceChildren();
  document.getElementById('resultsCount').textContent = translations[language].count(visible.length);

  if (!visible.length) {
    const empty = document.createElement('p');
    empty.className = 'empty-state';
    empty.textContent = translations[language].empty;
    grid.append(empty);
    return;
  }

  visible.forEach(property => {
    const card = document.createElement('article');
    card.className = 'property-card';

    const imageWrap = document.createElement('div');
    imageWrap.className = 'property-image-wrap';
    const image = document.createElement('img');
    image.className = 'property-image';
    image.src = property.image_url || 'imeges/1791317558139.jpg.jpeg';
    image.alt = `${property.title} — ${property.location}`;
    image.loading = 'lazy';
    const status = document.createElement('span');
    status.className = 'property-status';
    status.textContent = translations[language].status[property.status] || property.status;
    imageWrap.append(image, status);

    const details = document.createElement('div');
    details.className = 'property-details';
    const kind = document.createElement('p');
    kind.className = 'property-kind';
    kind.textContent = translations[language].kind;
    const title = document.createElement('h3');
    title.className = 'property-title';
    title.textContent = property.title;
    const location = document.createElement('p');
    location.className = 'property-location';
    location.textContent = property.location;
    details.append(kind, title, location);
    if (property.description) {
      const description = document.createElement('p');
      description.className = 'property-description';
      description.textContent = property.description;
      details.append(description);
    }
    card.append(imageWrap, details);
    grid.append(card);
  });
}

async function loadProperties() {
  const config = window.SITE_CONFIG || {};
  if (!config.supabaseUrl || !config.supabaseAnonKey) return;

  try {
    const endpoint = `${config.supabaseUrl.replace(/\/$/, '')}/rest/v1/properties?select=id,title,location,status,image_url,description&is_published=eq.true&order=created_at.desc`;
    const response = await fetch(endpoint, {
      headers: {
        apikey: config.supabaseAnonKey,
        Authorization: `Bearer ${config.supabaseAnonKey}`
      }
    });
    if (!response.ok) throw new Error(`Supabase returned HTTP ${response.status}`);
    const rows = await response.json();
    properties = Array.isArray(rows) && rows.length ? rows : sampleProperties;
    renderProperties();
  } catch (error) {
    console.error('Could not load properties from Supabase:', error);
    const notice = document.getElementById('siteNotice');
    notice.textContent = translations[language].fetchError;
    notice.hidden = false;
  }
}

